// Command openapi writes docs/openapi.json from the source of truth: the route registrations in
// internal/handler and internal/server (parsed with go/ast, so a route cannot be added without
// appearing here), guards detected from the wrappers around each handler, and the descriptions in
// docs/api-contract.md.
//
//	go run ./cmd/openapi           regenerate docs/openapi.json
//	go run ./cmd/openapi -check    fail when the committed file is out of date (CI runs this as a test)
//
// The spec is route-complete (method, path, path parameters, security, success status, description).
// Request and response bodies are described in prose in the contract, not as typed schemas.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

type route struct {
	Method, Path string
	Guards       []string
	Handler      string
}

func main() {
	check := flag.Bool("check", false, "fail if docs/openapi.json is out of date instead of writing it")
	flag.Parse()
	out, err := Build(".")
	if err != nil {
		fmt.Fprintln(os.Stderr, "openapi:", err)
		os.Exit(1)
	}
	path := filepath.Join("docs", "openapi.json")
	if *check {
		have, err := os.ReadFile(path)
		if err != nil || !bytes.Equal(have, out) {
			fmt.Fprintln(os.Stderr, "openapi: docs/openapi.json is out of date; run: go run ./cmd/openapi")
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(path, out, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "openapi:", err)
		os.Exit(1)
	}
	fmt.Println("wrote", path)
}

// Build renders the spec for the backend module rooted at root.
func Build(root string) ([]byte, error) {
	var routes []route
	for _, dir := range []string{"internal/handler", "internal/server"} {
		rs, err := parseRoutes(filepath.Join(root, dir))
		if err != nil {
			return nil, err
		}
		routes = append(routes, rs...)
	}
	if len(routes) == 0 {
		return nil, errors.New("no routes found")
	}
	docs := contractDocs(filepath.Join(root, "docs", "api-contract.md"))

	paths := map[string]map[string]any{}
	for _, r := range routes {
		if !documented(r.Path) {
			continue
		}
		oaPath := strings.NewReplacer("{key...}", "{key}").Replace(r.Path)
		op := operation(r, docs)
		if paths[oaPath] == nil {
			paths[oaPath] = map[string]any{}
		}
		if _, dup := paths[oaPath][strings.ToLower(r.Method)]; dup {
			return nil, fmt.Errorf("duplicate route %s %s", r.Method, r.Path)
		}
		paths[oaPath][strings.ToLower(r.Method)] = op
	}

	errResp := func(desc string) map[string]any {
		return map[string]any{"description": desc, "content": map[string]any{"application/json": map[string]any{"schema": map[string]any{"$ref": "#/components/schemas/Error"}}}}
	}
	spec := map[string]any{
		"openapi": "3.0.3",
		"info": map[string]any{
			"title":       "REDXTUBE API",
			"version":     "1.0.0",
			"description": "Generated by `go run ./cmd/openapi` from the route registrations; descriptions come from backend/docs/api-contract.md. Request and response bodies are documented there. Errors are `{code, message, fields?}`; clients branch on `code` and the `Retry-After` header.",
		},
		"servers": []any{map[string]any{"url": "/"}},
		"paths":   paths,
		"components": map[string]any{
			"securitySchemes": map[string]any{
				"sessionCookie": map[string]any{"type": "apiKey", "in": "cookie", "name": "xh_session", "description": "Session cookie set by POST /api/v1/auth/login. Unsafe methods also need an allowed Origin (CSRF)."},
				"ageCookie":     map[string]any{"type": "apiKey", "in": "cookie", "name": "xh_age", "description": "Signed age-gate cookie set by POST /api/v1/age/verify."},
				"streamToken":   map[string]any{"type": "apiKey", "in": "query", "name": "token", "description": "Not a query parameter: the token is the first path segment of /stream/{token}/... and is issued by GET /api/v1/videos/{id}."},
			},
			"schemas": map[string]any{
				"Error": map[string]any{"type": "object", "required": []string{"code", "message"}, "properties": map[string]any{
					"code":    map[string]any{"type": "string", "example": "video_not_found"},
					"message": map[string]any{"type": "string"},
					"fields":  map[string]any{"type": "object", "additionalProperties": map[string]any{"type": "string"}},
				}},
			},
			"responses": map[string]any{
				"BadRequest":   errResp("Validation failed (`validation_failed`, `invalid_cursor`, ...)"),
				"Unauthorized": errResp("No valid session"),
				"Forbidden":    errResp("Age verification, verified email, role or CSRF check failed"),
				"NotFound":     errResp("Not found (also used for content the caller may not see)"),
				"RateLimited":  errResp("Too many requests; see the Retry-After header"),
			},
		},
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(spec); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func documented(p string) bool {
	return strings.HasPrefix(p, "/api/v1/") || p == "/health" || p == "/ready" || strings.HasPrefix(p, "/stream/")
}

func operation(r route, docs map[string]string) map[string]any {
	tag := "system"
	switch {
	case strings.HasPrefix(r.Path, "/api/v1/"):
		tag = strings.SplitN(strings.TrimPrefix(r.Path, "/api/v1/"), "/", 2)[0]
	case strings.HasPrefix(r.Path, "/stream/"):
		tag = "stream"
	}
	desc := docs[key(r.Method, r.Path)]
	success := "200"
	if m := regexp.MustCompile(`-> (\d{3})`).FindStringSubmatch(desc); m != nil {
		success = m[1]
	}
	op := map[string]any{
		"tags":        []string{tag},
		"operationId": operationID(r),
		"summary":     r.Method + " " + strings.TrimPrefix(r.Path, "/api/v1"),
		"x-handler":   r.Handler,
	}
	if desc != "" {
		op["description"] = desc
	} else {
		op["description"] = "Not described in api-contract.md yet."
	}
	var params []any
	for _, m := range regexp.MustCompile(`\{([a-zA-Z_]+)(\.\.\.)?\}`).FindAllStringSubmatch(r.Path, -1) {
		params = append(params, map[string]any{"name": m[1], "in": "path", "required": true, "schema": map[string]any{"type": "string"}})
	}
	if params != nil {
		op["parameters"] = params
	}
	if r.Method == "POST" || r.Method == "PUT" || r.Method == "PATCH" {
		op["requestBody"] = map[string]any{"required": false, "content": map[string]any{"application/json": map[string]any{"schema": map[string]any{"type": "object"}}}}
	}
	okResp := map[string]any{"description": "Success"}
	if success != "204" {
		okResp["content"] = map[string]any{"application/json": map[string]any{"schema": map[string]any{"type": "object"}}}
	}
	if strings.HasPrefix(r.Path, "/stream/") {
		okResp = map[string]any{"description": "HLS playlist (application/vnd.apple.mpegurl) or MPEG-TS segment (video/mp2t)"}
	}
	resp := map[string]any{success: okResp, "429": map[string]any{"$ref": "#/components/responses/RateLimited"}}
	if r.Method != "GET" || len(params) > 0 {
		resp["400"] = map[string]any{"$ref": "#/components/responses/BadRequest"}
	}
	sec := map[string]any{}
	var notes []string
	for _, g := range r.Guards {
		switch g {
		case "age":
			sec["ageCookie"] = []string{}
		case "session":
			sec["sessionCookie"] = []string{}
		case "verified":
			sec["sessionCookie"] = []string{}
			notes = append(notes, "verified email")
		case "moderator", "admin":
			sec["sessionCookie"] = []string{}
			notes = append(notes, "role "+g+" or higher")
		}
	}
	switch {
	case strings.HasPrefix(r.Path, "/stream/"):
		resp["403"] = map[string]any{"$ref": "#/components/responses/Forbidden"}
		resp["404"] = map[string]any{"$ref": "#/components/responses/NotFound"}
		op["x-auth"] = "path token issued by GET /api/v1/videos/{id}"
	case len(sec) > 0:
		op["security"] = []any{sec}
		resp["403"] = map[string]any{"$ref": "#/components/responses/Forbidden"}
		if _, ok := sec["sessionCookie"]; ok {
			resp["401"] = map[string]any{"$ref": "#/components/responses/Unauthorized"}
		}
	default:
		op["security"] = []any{}
	}
	if len(notes) > 0 {
		op["x-requires"] = notes
	}
	if strings.Contains(r.Path, "{id}") || strings.Contains(r.Path, "{") {
		resp["404"] = map[string]any{"$ref": "#/components/responses/NotFound"}
	}
	op["responses"] = resp
	return op
}

func operationID(r route) string {
	var b strings.Builder
	b.WriteString(strings.ToLower(r.Method))
	for _, seg := range strings.Split(strings.TrimPrefix(r.Path, "/"), "/") {
		if seg == "" || seg == "api" || seg == "v1" {
			continue
		}
		seg = strings.Trim(strings.TrimSuffix(seg, "..."), "{}")
		if strings.Contains(seg, "-") {
			parts := strings.Split(seg, "-")
			seg = ""
			for _, p := range parts {
				seg += strings.ToUpper(p[:1]) + p[1:]
			}
		}
		b.WriteString(strings.ToUpper(seg[:1]) + seg[1:])
	}
	return b.String()
}

// ---------- route extraction ----------

func parseRoutes(dir string) ([]route, error) {
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, func(fi os.FileInfo) bool { return !strings.HasSuffix(fi.Name(), "_test.go") }, 0)
	if err != nil {
		return nil, err
	}
	var out []route
	for _, pkg := range pkgs {
		for _, f := range pkg.Files {
			for _, d := range f.Decls {
				fn, ok := d.(*ast.FuncDecl)
				if !ok || fn.Body == nil {
					continue
				}
				consts := map[string]string{}
				ast.Inspect(fn.Body, func(n ast.Node) bool {
					switch x := n.(type) {
					case *ast.ValueSpec:
						for i, name := range x.Names {
							if i < len(x.Values) {
								if s, ok := evalString(x.Values[i], consts); ok {
									consts[name.Name] = s
								}
							}
						}
					case *ast.AssignStmt:
						for i, l := range x.Lhs {
							if id, ok := l.(*ast.Ident); ok && i < len(x.Rhs) {
								if s, ok := evalString(x.Rhs[i], consts); ok {
									consts[id.Name] = s
								}
							}
						}
					case *ast.CallExpr:
						sel, ok := x.Fun.(*ast.SelectorExpr)
						if !ok || (sel.Sel.Name != "HandleFunc" && sel.Sel.Name != "Handle") || len(x.Args) != 2 {
							return true
						}
						pat, ok := evalString(x.Args[0], consts)
						if !ok {
							return true
						}
						method, p, found := strings.Cut(pat, " ")
						if !found {
							return true
						}
						out = append(out, route{Method: method, Path: p, Guards: guards(x.Args[1]), Handler: handlerName(x.Args[1])})
					}
					return true
				})
			}
		}
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].Path != out[j].Path {
			return out[i].Path < out[j].Path
		}
		return out[i].Method < out[j].Method
	})
	return out, nil
}

// evalString folds "GET " + v + "/x" where v is a string constant in the same function.
func evalString(e ast.Expr, consts map[string]string) (string, bool) {
	switch x := e.(type) {
	case *ast.BasicLit:
		if x.Kind == token.STRING {
			s, err := strconv.Unquote(x.Value)
			return s, err == nil
		}
	case *ast.Ident:
		s, ok := consts[x.Name]
		return s, ok
	case *ast.BinaryExpr:
		if x.Op == token.ADD {
			l, ok1 := evalString(x.X, consts)
			r, ok2 := evalString(x.Y, consts)
			return l + r, ok1 && ok2
		}
	case *ast.ParenExpr:
		return evalString(x.X, consts)
	}
	return "", false
}

var guardByName = map[string]string{
	"g": "age", "age": "age", "RequireAge": "age", "gate": "age",
	"auth_": "session", "RequireAuth": "session",
	"verified": "verified", "RequireVerified": "verified",
	"mod": "moderator", "adm": "admin",
}

func guards(e ast.Expr) []string {
	var out []string
	seen := map[string]bool{}
	ast.Inspect(e, func(n ast.Node) bool {
		c, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}
		name := ""
		switch f := c.Fun.(type) {
		case *ast.Ident:
			name = f.Name
		case *ast.SelectorExpr:
			name = f.Sel.Name
		}
		if g, ok := guardByName[name]; ok && !seen[g] {
			seen[g] = true
			out = append(out, g)
		}
		return true
	})
	sort.Strings(out)
	return out
}

func handlerName(e ast.Expr) string {
	name := ""
	ast.Inspect(e, func(n ast.Node) bool {
		if s, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := s.X.(*ast.Ident); ok && len(id.Name) <= 12 && (id.Name == "h" || id.Name == "health" || id.Name == "s") {
				name = s.Sel.Name
			}
		}
		return true
	})
	return name
}

// ---------- contract descriptions ----------

var paramRe = regexp.MustCompile(`\{[^}]*\}`)

func key(method, path string) string {
	p := strings.TrimPrefix(path, "/api/v1")
	return method + " " + paramRe.ReplaceAllString(p, "{}")
}

// contractDocs maps "METHOD /path" to "Auth: ... . <body -> result>" from the markdown tables.
func contractDocs(path string) map[string]string {
	b, err := os.ReadFile(path)
	out := map[string]string{}
	if err != nil {
		return out
	}
	tick := regexp.MustCompile("`([^`]+)`")
	for _, line := range strings.Split(string(b), "\n") {
		if !strings.HasPrefix(line, "| `") {
			continue
		}
		cells := strings.Split(strings.Trim(line, "| "), " | ")
		if len(cells) < 3 {
			continue
		}
		desc := "Auth: " + strings.TrimSpace(cells[1]) + ". " + strings.TrimSpace(strings.Join(cells[2:], " | "))
		method := ""
		for _, t := range tick.FindAllStringSubmatch(cells[0], -1) {
			tok := strings.TrimSpace(t[1])
			ms := []string{}
			if first, rest, ok := strings.Cut(tok, " "); ok && regexp.MustCompile(`^[A-Z/]+$`).MatchString(first) {
				ms = strings.Split(first, "/")
				method = first
				tok = rest
			} else if method != "" {
				ms = strings.Split(method, "/")
			}
			tok = strings.TrimSpace(strings.SplitN(tok, "?", 2)[0])
			if !strings.HasPrefix(tok, "/") {
				continue
			}
			for _, m := range ms {
				out[key(m, tok)] = desc
			}
		}
	}
	return out
}
